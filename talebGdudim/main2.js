let currentIndex = 0;
let currentTexts = [];

function initTextPage() {
    const sub = sessionStorage.getItem("selectedSub");
    if (!sub) return;

    currentTexts = texts[sub];

    // title
    const titleImg = document.querySelector(".title");
    if (titleImg) {
        titleImg.src = titles[sub];
    }

    currentIndex = 0;
    updateText();
}

function updateText() {
    const textDiv = document.querySelector(".text");
    const innerTitle = document.querySelector(".innerTitle");
    const forwardBtn = document.querySelector(".forwordBtn");
    const backBtn = document.querySelector(".backBtn");
    const optionsDiv = document.querySelector(".options");

    if (!textDiv) return;

    const currentItem = currentTexts[currentIndex];

    textDiv.innerText = currentItem.content;
    if (innerTitle) {
        innerTitle.innerText = currentItem.title;
    }

    // -----------------------------
    // OPTIONS (כפתורים מיוחדים)
    // -----------------------------
    optionsDiv.innerHTML = "";

    if (currentItem.options) {
        // hide רגילים
        forwardBtn.style.display = "none";
        backBtn.style.display = "none";

        currentItem.options.forEach(option => {
            const btn = document.createElement("button");
            btn.innerText = option.text;

            btn.onclick = () => {
                currentIndex = option.goTo;
                updateText();
            };

            optionsDiv.appendChild(btn);
        });

    } else {
        // רגיל
        if (backBtn) {
            backBtn.style.display = currentIndex === 0 ? "none" : "block";
        }

        if (forwardBtn) {
            forwardBtn.style.display = currentIndex === currentTexts.length - 1 ? "none" : "block";
        }
    }
}
// -----------------------------
// BUTTONS
// -----------------------------

document.querySelector(".forwordBtn")?.addEventListener("click", () => {
    currentIndex++;
    updateText();
});

document.querySelector(".backBtn")?.addEventListener("click", () => {
    currentIndex--;
    updateText();
});

// -----------------------------
// INIT
// -----------------------------

window.addEventListener("load", initTextPage);